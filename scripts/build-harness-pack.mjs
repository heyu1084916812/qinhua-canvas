function writeLauncher(root) {
  const bin = path.join(root, 'bin')
  mkdirSync(bin, { recursive: true })
  writeFileSync(
    path.join(bin, 'dsh.cmd'),
    [
      '@echo off',
      'setlocal',
      'if not defined QINGHUA_HARNESS_HOME exit /b 64',
      'set "DSH_HOME=%QINGHUA_HARNESS_HOME%"',
      '"%~dp0..\\node\\node.exe" "%~dp0..\\node_modules\\@deepseek-ai\\dsh\\lib\\bin.js" %*',
      '',
    ].join('\r\n'),
    'ascii',
  )
}

function zipDirectory(source, destination) {
  rmSync(destination, { force: true })
  run('powershell.exe', [
    '-NoProfile',
    '-Command',
    [
      'Add-Type -AssemblyName System.IO.Compression.FileSystem;',
      '[System.IO.Compression.ZipFile]::CreateFromDirectory(',
      '$env:QINGHUA_ZIP_SOURCE,$env:QINGHUA_ZIP_TARGET,',
      '[System.IO.Compression.CompressionLevel]::Optimal,$false)',
    ].join(' '),
  ], {
    env: {
      ...process.env,
      QINGHUA_ZIP_SOURCE: source,
      QINGHUA_ZIP_TARGET: destination,
    },
  })
}

function signPack(packPath) {
  const keyPath =
    process.env.QINGHUA_HARNESS_SIGNING_KEY ??
    path.join(homedir(), '.tauri', 'qinghua-updater.key')
  if (!existsSync(keyPath)) {
    fail(`找不到 Harness 资源包签名私钥：${keyPath}`)
  }
  const tauri = path.join(ROOT, 'node_modules', '@tauri-apps', 'cli', 'tauri.js')
  run(process.execPath, [
    tauri,
    'signer',
    'sign',
    '--app-version',
    HARNESS_VERSION,
    '--private-key-path',
    keyPath,
    packPath,
  ])
}

function unpackMinisign(outerBase64) {
  const text = Buffer.from(String(outerBase64 ?? '').trim(), 'base64').toString('utf8')
  const line = text
    .split(/\r?\n/u)
    .map((entry) => entry.trim())
    .find((entry) => /^[A-Za-z0-9+/=]{40,}$/u.test(entry))
  if (!line) throw new Error('Minisign 文本缺少 base64 数据行')
  return Buffer.from(line, 'base64')
}

function verifyPackSignature(packPath) {
  const conf = JSON.parse(
    readFileSync(path.join(ROOT, 'src-tauri', 'tauri.conf.json'), 'utf8'),
  )
  const publicKey = unpackMinisign(conf?.plugins?.updater?.pubkey)
  const signature = unpackMinisign(readFileSync(`${packPath}.sig`, 'utf8'))
  const publicKeyId = publicKey.subarray(2, 10).toString('hex')
  const signatureKeyId = signature.subarray(2, 10).toString('hex')
  if (publicKeyId !== signatureKeyId) {
    fail(`Harness 资源包签名 keyid 不匹配：${signatureKeyId} != ${publicKeyId}`)
  }
  const spkiPrefix = Buffer.from('302a300506032b6570032100', 'hex')
  const key = createPublicKey({
    key: Buffer.concat([spkiPrefix, publicKey.subarray(10, 42)]),
    format: 'der',
    type: 'spki',
  })
  const digest = createHash('blake2b512').update(readFileSync(packPath)).digest()
  if (!verify(null, digest, key, signature.subarray(10, 74))) {
    fail('Harness 资源包 Ed25519 验签失败')
  }
  console.log(`[harness-pack] signature verified with updater key ${signatureKeyId}`)
}

function nodeLicense(version) {
  const cache = path.join(BUILD_ROOT, `node-v${version}-LICENSE.txt`)
  if (existsSync(cache)) return readFileSync(cache, 'utf8')
  const url = `https://raw.githubusercontent.com/nodejs/node/v${version}/LICENSE`
  run('powershell.exe', [
    '-NoProfile',
    '-Command',
    [
      '$ProgressPreference="SilentlyContinue"; Invoke-WebRequest -UseBasicParsing',
      `-Uri '${url}'`,
      `-OutFile '${cache}'`,
      '-TimeoutSec 60',
    ].join(' '),
  ])
  return readFileSync(cache, 'utf8')
}

if (process.platform !== 'win32' || process.arch !== 'x64') {
  fail('Harness Windows x64 资源包必须在 Windows x64 构建机上生成')
}

const nodeVersion = execFileSync(process.execPath, ['--version'], {
  encoding: 'utf8',
}).trim()
if (!versionAtLeast(nodeVersion, HARNESS_MIN_NODE)) {
  fail(`构建 Harness 需要 Node >= ${HARNESS_MIN_NODE}，当前 ${nodeVersion}`)
}

mkdirSync(BUILD_ROOT, { recursive: true })
mkdirSync(OUT_DIR, { recursive: true })
const installedPackage = path.join(
  STAGING,
  'node_modules',
  '@deepseek-ai',
  'dsh',
  'package.json',
)
const installedVersion = existsSync(installedPackage)
  ? JSON.parse(readFileSync(installedPackage, 'utf8')).version
  : null
if (installedVersion !== HARNESS_VERSION) {
  rmSync(STAGING, { recursive: true, force: true })
  mkdirSync(STAGING, { recursive: true })
  const reusable = process.env.QINGHUA_HARNESS_INSTALL_FROM
  if (reusable) {
    const source = path.resolve(reusable)
    if (!existsSync(path.join(source, 'node_modules'))) {
      fail(`QINGHUA_HARNESS_INSTALL_FROM 缺少 node_modules：${source}`)
    }
    copyDirectory(
      path.join(source, 'node_modules'),
      path.join(STAGING, 'node_modules'),
    )
    if (existsSync(path.join(source, 'package.json'))) {
      copyFileSync(path.join(source, 'package.json'), path.join(STAGING, 'package.json'))
    }
  } else {
    run(
      process.platform === 'win32' ? 'npm.cmd' : 'npm',
      [
        'install',
        '--prefix',
        STAGING,
        '--omit=dev',
        '--no-audit',
        '--no-fund',
        `@deepseek-ai/dsh@${HARNESS_VERSION}`,
      ],
      { cwd: ROOT },
    )
  }
}

for (const relative of [
  path.join('node_modules', '@deepseek-ai', 'dsh', 'package.json'),
  path.join('node_modules', '@deepseek-ai', 'dsh', 'lib', 'bin.js'),
]) {
  if (!existsSync(path.join(STAGING, relative))) {
    fail(`DSH 安装不完整，缺少 ${relative}`)
  }
}

const nodeDir = path.join(STAGING, 'node')
mkdirSync(nodeDir, { recursive: true })
copyFileSync(process.execPath, path.join(nodeDir, 'node.exe'))
writeFileSync(
  path.join(nodeDir, 'LICENSE'),
  nodeLicense(nodeVersion.replace(/^v/u, '')),
  'utf8',
)
copyFileSync(
  path.join(STAGING, 'node_modules', '@deepseek-ai', 'dsh', 'LICENSE'),
  path.join(STAGING, 'DSH-LICENSE.txt'),
)
writeFileSync(
  path.join(STAGING, 'THIRD_PARTY_NOTICES.txt'),
  [
    `DeepSeek Harness @deepseek-ai/dsh ${HARNESS_VERSION}`,
    `Source: https://github.com/deepseek-ai/deepseek-harness/tree/dsh-v${HARNESS_VERSION}`,
    `Commit: ${HARNESS_COMMIT}`,
    'License: MIT (DSH-LICENSE.txt)',
    '',
    `Node.js ${nodeVersion}`,
    'License: Node.js project license (node/LICENSE)',
    '',
  ].join('\n'),
  'utf8',
)
writeLauncher(STAGING)
writeProfile(STAGING)

const manifest = {
  formatVersion: PACK_FORMAT_VERSION,
  packName: PACK_NAME,
  platform: 'windows-x64',
  harness: {
    package: '@deepseek-ai/dsh',
    version: HARNESS_VERSION,
    tag: `dsh-v${HARNESS_VERSION}`,
    commit: HARNESS_COMMIT,
    entry: 'bin/dsh.cmd',
    profile: 'profile/acp',
  },
  node: {
    version: nodeVersion,
    minimum: `v${HARNESS_MIN_NODE}`,
    executable: 'node/node.exe',
  },
  provider: {
    id: 'qinghua-local',
    model: HARNESS_AGENT_MODEL,
    urlEnv: PROVIDER_URL_ENV,
    tokenEnv: PROVIDER_TOKEN_ENV,
  },
  builtAt: new Date().toISOString(),
}
writeFileSync(
  path.join(STAGING, 'manifest.json'),
  `${JSON.stringify(manifest, null, 2)}\n`,
  'utf8',
)

console.log(`[harness-pack] staging ${STAGING}`)
zipDirectory(STAGING, PACK_PATH)
signPack(PACK_PATH)
verifyPackSignature(PACK_PATH)

const signaturePath = `${PACK_PATH}.sig`
const packBytes = statSync(PACK_PATH).size
const packSha256 = sha256(PACK_PATH)
const signature = readFileSync(signaturePath, 'utf8').trim()
const releaseManifest = {
  ...manifest,
  pack: {
    file: PACK_NAME,
    bytes: packBytes,
    sha256: packSha256,
    signatureFile: `${PACK_NAME}.sig`,
    signature,
  },
}
writeFileSync(
  path.join(OUT_DIR, `qinghua-harness_${HARNESS_VERSION}_x64.json`),
  `${JSON.stringify(releaseManifest, null, 2)}\n`,
  'utf8',
)

console.log('\n[harness-pack] complete')
console.log(`  pack: ${path.relative(ROOT, PACK_PATH)} (${packBytes} B)`)
console.log(`  sha256: ${packSha256}`)
console.log(`  signature: ${path.relative(ROOT, signaturePath)}`)
