#!/usr/bin/env node
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs'
import { createHash, createPublicKey, verify } from 'node:crypto'
import { homedir } from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { execFileSync, spawnSync } from 'node:child_process'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const HARNESS_VERSION = process.env.QINGHUA_HARNESS_VERSION ?? '0.2.2-alpha.2'
const HARNESS_COMMIT =
  process.env.QINGHUA_HARNESS_COMMIT ??
  'f3803c96974ad4a94195fb97e5c637e9c2a3afe3'
const HARNESS_MIN_NODE = '24.9.0'
const HARNESS_AGENT_MODEL = 'qinghua-agent'
const PROVIDER_URL_ENV = 'QINGHUA_PROVIDER_URL'
const PROVIDER_TOKEN_ENV = 'QINGHUA_PROVIDER_TOKEN'
const PACK_FORMAT_VERSION = 1
const BUILD_ROOT = path.join(ROOT, '.harness-pack', HARNESS_VERSION)
const STAGING = path.join(BUILD_ROOT, 'staging')
const OUT_DIR = path.join(ROOT, 'release', 'harness', HARNESS_VERSION)
const PACK_NAME = `qinghua-harness_${HARNESS_VERSION}_x64.zip`
const PACK_PATH = path.join(OUT_DIR, PACK_NAME)

function fail(message) {
  throw new Error(message)
}

function run(command, args, options = {}) {
  const result = spawnSync(command, args, {
    cwd: options.cwd ?? ROOT,
    env: options.env ?? process.env,
    stdio: 'inherit',
    windowsHide: true,
  })
  if (result.error) throw result.error
  const allowed = options.allowedStatuses ?? [0]
  if (!allowed.includes(result.status)) {
    fail(`${command} ${args.join(' ')} failed with exit code ${result.status}`)
  }
}

function copyDirectory(source, destination) {
  run(
    'robocopy.exe',
    [
      source,
      destination,
      '/E',
      '/COPY:DAT',
      '/DCOPY:DAT',
      '/R:2',
      '/W:2',
      '/NFL',
      '/NDL',
      '/NJH',
      '/NJS',
      '/NP',
    ],
    { allowedStatuses: [0, 1, 2, 3, 4, 5, 6, 7] },
  )
}

function parseVersion(value) {
  const match = /^v?(\d+)\.(\d+)\.(\d+)/u.exec(value.trim())
  if (!match) fail(`无法读取版本号：${value}`)
  return match.slice(1).map(Number)
}

function versionAtLeast(actual, minimum) {
  const left = parseVersion(actual)
  const right = parseVersion(minimum)
  for (let index = 0; index < 3; index += 1) {
    if (left[index] !== right[index]) return left[index] > right[index]
  }
  return true
}

function sha256(file) {
  return createHash('sha256').update(readFileSync(file)).digest('hex').toUpperCase()
}

