export const HARNESS_AGENT_MODEL = 'qinghua-agent'
export const HARNESS_PROVIDER_URL_ENV = 'QINGHUA_PROVIDER_URL'
export const HARNESS_PROVIDER_TOKEN_ENV = 'QINGHUA_PROVIDER_TOKEN'

export interface HarnessHttpMcpServer {
  name: string
  type: 'http'
  url: string
  headers: { name: string; value: string }[]
}

export function harnessHttpMcpServer(input: {
  name?: string
  url: string
  token: string
}): HarnessHttpMcpServer {
  const name = input.name?.trim() || 'qinghua-canvas'
  if (!/^[A-Za-z0-9_-]{1,32}$/u.test(name)) {
    throw new Error('Harness MCP 服务名只能使用 1-32 位字母、数字、下划线或连字符')
  }
  const url = new URL(input.url)
  if (url.protocol !== 'http:' && url.protocol !== 'https:') {
    throw new Error('Harness MCP 地址必须是 HTTP(S) 绝对地址')
  }
  if (!input.token.trim()) throw new Error('Harness MCP Bearer token 不能为空')
  return {
    name,
    type: 'http',
    url: url.toString(),
    headers: [{ name: 'Authorization', value: `Bearer ${input.token}` }],
  }
}

/**
 * DSH acp profile 的唯一模型入口。
 *
 * Worker 只认识固定的 qinghua-agent；真正的轻画模型由本地 provider 桥按
 * 当前会话选择解析，避免把渠道 Key、模型列表和重试规则复制进 Harness。
 */
export function buildHarnessAcpProfilePatch(): string {
  return [
    '# Generated by 轻画. Do not edit: the sidecar is replaced as a signed pack.',
    '- id: llm-retry',
    '  disabled: true',
    '- id: llm-deepseek',
    '  disabled: true',
    '- id: llm-deepseek-account',
    '  disabled: true',
    '- id: session-log-deepseek',
    '  disabled: true',
    '- id: llm-pi-ai',
    '  config:',
    '    providers:',
    '      qinghua-local:',
    `        apiKeyEnv: ${HARNESS_PROVIDER_TOKEN_ENV}`,
    '        api: openai-completions',
    `        baseURL: !!js process.env.${HARNESS_PROVIDER_URL_ENV}`,
    '        defaultInput: [text, image]',
    '        compat:',
    '          supportsDeveloperRole: false',
    '          maxTokensField: max_tokens',
    '        models:',
    `          - id: ${HARNESS_AGENT_MODEL}`,
    '            name: 轻画 Agent',
    '            input: [text, image]',
    '- id: agent-default-model',
    '  config:',
    '    provider: qinghua-local',
    `    model: ${HARNESS_AGENT_MODEL}`,
    '- id: acp',
    '  config:',
    '    provider: qinghua-local',
    `    model: ${HARNESS_AGENT_MODEL}`,
    '',
  ].join('\n')
}
